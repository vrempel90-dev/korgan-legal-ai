def _section(heading: str, clauses: list) -> dict:
    normalized = []
    for clause in clauses:
        if isinstance(clause, str):
            normalized.append({"text": clause, "subclauses": []})
        else:
            normalized.append({"text": clause[0], "subclauses": list(clause[1])})
    return {"heading": heading, "clauses": normalized}


