def _contract_payload(title: str, subject_sections: list[dict], *, dirty: bool = False) -> dict:
    """Assemble a contract payload; ``dirty`` reproduces the shipped numbering defect."""
    sections = subject_sections + _COMMON_TAIL
    if dirty:
        sections = [
            {
                "heading": f"{index}. {section['heading']}",
                "clauses": [
                    {
                        "text": f"{index}.{position}. {clause['text']}",
                        "subclauses": clause["subclauses"],
                    }
                    for position, clause in enumerate(section["clauses"], start=1)
                ],
            }
            for index, section in enumerate(sections, start=1)
        ]
    return {
        "contract_type": title.lower(),
        "title": title.upper(),
        "place_and_date": "г. Алматы, 16 августа 2026 года",
        "party_a": [_PARTY_A],
        "party_b": [_PARTY_B],
        "preamble": [_GOOD_PREAMBLE],
        "sections": sections,
        "requisites_a": [_PARTY_A, "[ТРЕБУЕТ УТОЧНЕНИЯ: адрес и банковские реквизиты]"],
        "requisites_b": [_PARTY_B, "[ТРЕБУЕТ УТОЧНЕНИЯ: адрес и банковские реквизиты]"],
        "verification_notes": [],
    }


