"""Статус истца, названный в материалах словами, а не только через ИИН.

Ставка государственной пошлины по статье 665 НК РК зависит от того, физическое
или юридическое лицо предъявляет иск. Раньше этот факт извлекался только из
идентификатора: ИИН в блоке истца — физическое лицо, БИН или организационная
форма — юридическое. Клиент, который прямо написал «Статус: физическое лицо», но
не назвал свой ИИН, оставался неопределённым, и пошлина по полностью
определённой цене иска не рассчитывалась.

Обратная сторона симметрична и уже работала: «юридическое лицо» в блоке истца
распознавалось. Здесь закрывается только вторая половина той же пары.
"""

from __future__ import annotations

from korgan.legal_calc import claimant_is_individual


def test_explicit_individual_status_is_read_from_the_claimant_block() -> None:
    context = (
        "Истец: Сериков Арман Нурланович\n"
        "Статус: физическое лицо\n"
        "Адрес проживания: город Алматы, улица Тестовая, дом 25, квартира 18\n"
        "Ответчик: ТОО «Мебель Стандарт»\n"
    )

    assert claimant_is_individual(context) is True


def test_kazakh_status_wording_inside_the_claimant_block() -> None:
    """Казахская формулировка статуса читается там, где блок истца уже разобран.

    Сам заголовок «Талап қоюшы:» разбором ролей пока не поддерживается — это
    отдельный пробел казахской ветки, и здесь он не закрывается.
    """
    context = "Истец: Сериков Арман Нурланович, жеке тұлға\nОтветчик: ТОО «Мебель Стандарт»\n"

    assert claimant_is_individual(context) is True


def test_legal_entity_marker_still_wins_over_the_word_individual() -> None:
    """Организационная форма сильнее слова: ТОО не становится физическим лицом."""
    context = (
        "Истец: ТОО «Мебель Стандарт», интересы которого затронуты как физического лица\n"
        "Ответчик: Сериков Арман Нурланович\n"
    )

    assert claimant_is_individual(context) is False


def test_defendant_status_does_not_decide_the_claimant() -> None:
    """Статус названного рядом ответчика ставку пошлины истца не определяет."""
    context = "Истец: ТОО «Мебель Стандарт»\nОтветчик: Сериков Арман Нурланович, физическое лицо\n"

    assert claimant_is_individual(context) is False
