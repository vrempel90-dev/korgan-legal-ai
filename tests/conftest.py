"""Окружение тестов задаётся здесь, а не в голове запускающего.

Зачем файл существует
---------------------
`Settings` требует `TELEGRAM_BOT_TOKEN` и `OPENAI_API_KEY`, а `korgan.miniapp_api`
собирает настройки прямо при импорте. Без этих переменных `pytest` не доходил
даже до запуска тестов: два десятка файлов падали на сборе с ValidationError.
Нигде в репозитории не было записано, что именно нужно выставить, — знание жило
в командной строке того, кто уже запускал набор раньше. Из чистого клона набор
не запускался вовсе.

Второе назначение — изоляция от окружения разработчика. `pydantic-settings`
читает переменные среды, и они сильнее умолчаний. Достаточно, чтобы в оболочке
оказался посторонний `ANTHROPIC_MODEL` (его выставляют инструменты, работающие
с тем же API), и настройки тестов молча подменялись: результат зависел от того,
на какой машине запущен набор. Ошибка при этом выглядела как провал логики, а не
как загрязнение среды.

Значения здесь заведомо ненастоящие. Ни один тест не ходит в сеть, а ключ, по
которому можно было бы сходить, в наборе тестов не нужен и не должен появиться.
"""

from __future__ import annotations

import os

# Обязательные поля Settings. Проставляются только если их нет: окружение,
# которое сознательно задало своё значение, не перетирается.
for name, value in (
    ("TELEGRAM_BOT_TOKEN", "test-token"),
    ("OPENAI_API_KEY", "test-key"),
):
    os.environ.setdefault(name, value)

# Переменные, которые в тестах обязаны быть выключены. Провайдера и модели
# каждый тест задаёт явно, поэтому унаследованное значение может только исказить
# результат. `ANTHROPIC_API_KEY` снимается ещё и потому, что с ним `Settings`
# сам выбрал бы Anthropic основным провайдером, и тесты стали бы проверять не ту
# ветку, которую собирались.
for name in (
    "ANTHROPIC_API_KEY",
    "ANTHROPIC_MODEL",
    "ANTHROPIC_VISION_MODEL",
    "ANTHROPIC_VALIDATION_MODEL",
    "AI_PROVIDER",
):
    os.environ.pop(name, None)
