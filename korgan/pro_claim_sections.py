"""Профессиональные разделы искового заявления.

Поля расширяют базовую схему иска без ломки старых сохранённых черновиков.
Клиентский судебный документ строится как связная цепочка:

    факт → доказательство → норма → вывод → требование

Дополнительно хранятся процессуальные сведения: подсудность, расчёт взыскиваемых
сумм, досудебный порядок, меры к примирению, исковая давность и ходатайства.

Поле ``anticipated_defenses`` сохранено только для обратной совместимости со
старыми strict-схемами и сохранёнными payload. В судебный иск оно не выводится:
прогнозировать за ответчика будущие возражения отдельным разделом в исковом
заявлении не требуется. Фактически уже заявленные и подтверждённые материалами
возражения могут учитываться в обычном изложении фактов и правовой позиции.
"""

from __future__ import annotations

from typing import Any

from korgan.legal_types import ClaimDraft

# Новые свойства схемы иска. anticipated_defenses остаётся в схеме только для
# совместимости, но новый runtime всегда требует возвращать для него [].
PRO_CLAIM_PROPERTIES: dict[str, Any] = {
    "jurisdiction_reason": {"type": "string"},
    "calculation": {"type": "array", "items": {"type": "string"}},
    "pretrial_compliance": {"type": "string"},
    "reconciliation_measures": {"type": "string"},
    "limitation_period": {"type": "string"},
    "anticipated_defenses": {"type": "array", "items": {"type": "string"}},
    "motions": {"type": "array", "items": {"type": "string"}},
}

PRO_CLAIM_FIELDS: tuple[str, ...] = tuple(PRO_CLAIM_PROPERTIES)


def extend_claim_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """Добавить профессиональные разделы в strict-схему иска на месте."""
    schema["properties"].update(PRO_CLAIM_PROPERTIES)
    required = schema.setdefault("required", [])
    for name in PRO_CLAIM_FIELDS:
        if name not in required:
            required.append(name)
    return schema


def pro_payload(draft: ClaimDraft) -> dict[str, Any]:
    """Профессиональные разделы черновика для раунда правки."""
    return {
        "jurisdiction_reason": draft.jurisdiction_reason,
        "calculation": list(draft.calculation),
        "pretrial_compliance": draft.pretrial_compliance,
        "reconciliation_measures": draft.reconciliation_measures,
        "limitation_period": draft.limitation_period,
        # Совместимость схемы: наружу не печатается и в новом проекте пусто.
        "anticipated_defenses": [],
        "motions": list(draft.motions),
    }


def pro_text(draft: ClaimDraft) -> list[str]:
    """Судебно-значимые строки профессиональных разделов для QA-сканеров."""
    return [
        draft.jurisdiction_reason,
        draft.pretrial_compliance,
        draft.reconciliation_measures,
        draft.limitation_period,
        *draft.calculation,
        *draft.motions,
    ]


PRO_CLAIM_PROMPT = """

ПРОФЕССИОНАЛЬНЫЕ РАЗДЕЛЫ
Заполняй разделы только данными из материалов и VERIFIED. Пустым оставляй лишь
тот раздел, для которого действительно нет исходных данных.

jurisdiction_reason — почему иск подаётся именно в этот суд: родовая и
территориальная подсудность со ссылкой на подтверждённую норму ГПК РК и статус
сторон. Не определяй экономический суд по одному наличию ТОО.

calculation — отдельный и полноценный «Расчёт взыскиваемых сумм». Он ОБЯЗАТЕЛЕН,
если заявлено хотя бы одно денежное требование. Отдельной строкой покажи каждую
составляющую: основной долг, договорную неустойку/пеню, проценты, убытки,
подтверждённые расходы на юридические услуги/представителя и иные заявленные
судебные расходы. Для каждой расчётной составляющей укажи основание, базу,
ставку (если есть), период, формулу и итог. Итог расчёта должен совпадать с
просительной частью и ценой иска в той части, которая включается в цену иска.

Для ДОГОВОРНОЙ неустойки используй именно пункт договора и согласованную
сторонами ставку из материалов. Не подменяй договорную неустойку расчётом по
статье 353 ГК РК. Если в материалах есть ставка, база и даты/период — расчёт
неустойки нельзя пропускать. Если одного из необходимых элементов нет, сумму не
выдумывай: укажи недостающий элемент в verification_notes.

Если истец просит взыскать расходы на юридические услуги/представителя и в
материалах есть сумма и подтверждающий договор, акт, счёт или платёжный
документ, включи эти расходы отдельной строкой calculation и отдельным пунктом
requests. Если сумма или подтверждение отсутствуют, не придумывай их и укажи
пробел в verification_notes.

Если долг или неустойка гасились частично, разбей период по датам погашения.
Сумму государственной пошлины не считай: её считает детерминированный код.

pretrial_compliance — обязателен ли досудебный порядок по закону или договору,
что и когда направлено ответчику, каким документом подтверждается отправка и
вручение, поступил ли ответ. Если обязательный досудебный порядок не соблюдён,
отрази это в verification_notes, не выдумывай претензию.

reconciliation_measures — только фактически предпринятые действия, направленные
на примирение: переговоры, предложение рассрочки, медиация. Не выдумывай их.

limitation_period — срок исковой давности: начало течения, истечение, перерыв или
приостановление только по фактам материалов и подтверждённым нормам.

anticipated_defenses — СЛУЖЕБНОЕ ПОЛЕ СОВМЕСТИМОСТИ. ВСЕГДА возвращай пустой
массив []. Не создавай в исковом заявлении раздел «Возражения ответчика»,
«Возможные возражения ответчика», «Позиция ответчика» и не пиши рассуждения
«ответчик может утверждать/возражать/представить возражения». Если ответчик уже
фактически заявил конкретное возражение и это подтверждено материалами, его
можно кратко отразить как состоявшийся факт и дать правовую оценку в обычном
изложении, без отдельного прогнозного раздела.

motions — ходатайства, заявляемые вместе с иском: об обеспечении иска, об
истребовании доказательств, отсрочке госпошлины, вызове свидетеля. Заявляй
только те, для которых в материалах есть фактическое и правовое основание.

СВЯЗНОСТЬ ДОКУМЕНТА
Каждый пункт legal_basis должен назвать обстоятельство, к которому применяется
норма, и закончиться правовым выводом. Каждый пункт просительной части должен
следовать из фактов, расчёта и правового основания. Не добавляй абзацы, которые
не помогают доказать заявленное требование.

ЧЕСТНОСТЬ ССЫЛОК
Правовое обоснование строится на VERIFIED. Если необходимой нормы нет в VERIFIED,
не выдумывай номер статьи и не выдавай неподтверждённое за установленное: помести
в verification_notes указание, какую норму необходимо дополнительно проверить.
"""
