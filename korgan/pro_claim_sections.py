"""Профессиональные разделы искового заявления.

Что было не так
---------------
Схема иска состояла из пяти плоских списков строк: facts, legal_basis,
requests, attachments, verification_notes. Профессиональный иск — не три
списка рядом, а цепочка

    факт → доказательство → норма → вывод → требование

плюс процессуальный слой, которого в схеме не было вовсе: обоснование
подсудности, расчёт взыскиваемых сумм по составляющим, сведения о досудебном
порядке и мерах к примирению, исковая давность, снятие возражений ответчика,
ходатайства. Из-за отсутствия полей модель их и не писала: то, чего нет в
схеме, в документ не попадает, сколько ни проси в промпте.

Почему поля добавлены, а старые не переделаны
----------------------------------------------
Заменить `facts: list[str]` на массив объектов было бы правильнее по форме, но
на этих полях завязаны все guard'ы, финализаторы, тесты и три экспортёра Word.
Ломать их разом опаснее, чем получить выигрыш. Поэтому старые поля сохранены
как есть, а связность цепочки требуется промптом: каждый пункт legal_basis
обязан называть обстоятельство, к которому применяется, и заканчиваться
выводом.

Все поля обязательны в strict-схеме и приходят пустыми, когда для них нет
материала, — так молчание модели видно, а не выглядит как забытое поле.
"""

from __future__ import annotations

from typing import Any

from korgan.legal_types import ClaimDraft

# Новые свойства схемы иска. Порядок совпадает с порядком разделов документа.
PRO_CLAIM_PROPERTIES: dict[str, Any] = {
    "jurisdiction_reason": {"type": "string"},
    "calculation": {"type": "array", "items": {"type": "string"}},
    "pretrial_compliance": {"type": "string"},
    "reconciliation_measures": {"type": "string"},
    "limitation_period": {"type": "string"},
    "anticipated_defenses": {"type": "array", "items": {"type": "string"}},
    "motions": {"type": "array", "items": {"type": "string"}},
}

PRO_CLAIM_FIELDS: tuple[str, ...] = tuple(PRO_CLAIM_PROPERTIES)


def extend_claim_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """Добавить профессиональные разделы в strict-схему иска на месте."""
    schema["properties"].update(PRO_CLAIM_PROPERTIES)
    required = schema.setdefault("required", [])
    for name in PRO_CLAIM_FIELDS:
        if name not in required:
            required.append(name)
    return schema


def pro_payload(draft: ClaimDraft) -> dict[str, Any]:
    """Профессиональные разделы черновика — для передачи в раунд правки.

    Без этого раунд правки возвращал бы иск без расчёта, подсудности и
    ходатайств: чего нет во входном payload, того модель не восстановит.
    """
    return {
        "jurisdiction_reason": draft.jurisdiction_reason,
        "calculation": list(draft.calculation),
        "pretrial_compliance": draft.pretrial_compliance,
        "reconciliation_measures": draft.reconciliation_measures,
        "limitation_period": draft.limitation_period,
        "anticipated_defenses": list(draft.anticipated_defenses),
        "motions": list(draft.motions),
    }


def pro_text(draft: ClaimDraft) -> list[str]:
    """Все текстовые строки профессиональных разделов — для QA-сканеров."""
    return [
        draft.jurisdiction_reason,
        draft.pretrial_compliance,
        draft.reconciliation_measures,
        draft.limitation_period,
        *draft.calculation,
        *draft.anticipated_defenses,
        *draft.motions,
    ]


# Инструкция дописывается к промптам составления и правки иска. Она намеренно
# сформулирована через то, ЧТО юрист делает в каждом разделе, а не через
# запреты: из одних запретов документ не рождается, модель выдаёт минимальный
# безопасный текст.
PRO_CLAIM_PROMPT = """

ПРОФЕССИОНАЛЬНЫЕ РАЗДЕЛЫ (заполняются всегда; пустыми остаются только те, для \
которых в материалах нет ничего)

jurisdiction_reason — почему иск подаётся именно в этот суд: родовая и \
территориальная подсудность со ссылкой на норму ГПК РК и на статус сторон. Не \
определяй экономический суд по одному наличию ТОО.

calculation — расчёт взыскиваемых сумм по составляющим, отдельной строкой на \
каждую: основной долг, неустойка, проценты, убытки. В строке должны быть \
основание (пункт договора или норма), период начисления, формула и итог. \
Если долг гасился частично, разбей период по датам погашения — единая строка \
на весь срок будет арифметически неверной и даст ответчику готовое \
возражение. Сумму государственной пошлины не считай: её считает \
детерминированный код. Проверь, что итог расчёта совпадает с суммами в \
просительной части.

pretrial_compliance — обязателен ли досудебный порядок по закону или договору, \
что и когда направлено ответчику, каким документом подтверждается отправка и \
вручение, поступил ли ответ. Если досудебный порядок обязателен, а претензии \
не было, напиши это прямо: иначе суд вернёт иск.

reconciliation_measures — сведения о действиях, направленных на примирение \
(переговоры, предложение рассрочки, медиация). Указывать их требует часть 2 \
статьи 148 ГПК РК.

limitation_period — срок исковой давности: когда началось течение, истекает ли \
он, есть ли перерыв или приостановление. Частичная оплата долга ответчиком \
прерывает течение срока — если такой факт есть в материалах, выведи перерыв \
именно из него.

anticipated_defenses — два-три сильнейших возражения, которые заявит ответчик, \
и ответ на каждое со ссылкой на обстоятельство или норму. Формат строки: \
«Ответчик может утверждать, что … — однако …». Возражения снимаются в самом \
иске, до того как оппонент их заявит.

motions — ходатайства, заявляемые вместе с иском: об обеспечении иска, об \
истребовании доказательств, находящихся у ответчика или третьего лица, об \
отсрочке уплаты государственной пошлины, о вызове свидетеля. Заявляй только \
те, для которых в материалах есть основание.

СВЯЗНОСТЬ ДОКУМЕНТА
Каждый пункт legal_basis обязан назвать обстоятельство, к которому применяется \
норма, и закончиться правовым выводом, а не просто перечислить статью. Каждый \
пункт просительной части обязан опираться на норму из legal_basis. Каждый \
спорный факт обязан заканчиваться указанием доказательства и номера \
приложения. Звено, которое ни с чем не соединено, в документе не нужно.

ЧЕСТНОСТЬ ССЫЛОК
Если норма, необходимая для обоснования требования, отсутствует в VERIFIED, \
всё равно дай правовое обоснование: назови акт и статью, изложи правило своими \
словами БЕЗ кавычек и внеси в verification_notes требование сверить редакцию. \
Иск без правового обоснования хуже, чем обоснование с честной пометкой о \
необходимости сверки. Дословные цитаты в кавычках допустимы только для норм \
из VERIFIED.
"""
