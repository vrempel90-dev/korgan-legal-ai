"""Защита от подмены вида договора при разработке цифрового продукта.

Разработка сайта, интернет-магазина или мобильного приложения внешне похожа на
проектные работы: заказчик, подрядчик, техническое задание, этапы, сдача
результата. Отсюда типичная ошибка — применить к ней параграф ГК РК о подряде на
проектные и изыскательские работы либо о строительном подряде.

Эти параграфы написаны про другое: про проектную документацию и изыскания для
строительства, задание на проектирование, согласование документации с
уполномоченными органами, ответственность за недостатки проекта и объекта.
К разработке программного продукта они не относятся, и построенное на них
правовое обоснование оппонент снимает первым же абзацем.

Модуль не выбирает правильный вид договора — выбор нормы остаётся за моделью и
юристом. Он лишь не даёт выпустить документ с квалификацией, которую материалы
дела прямо опровергают: цифровой предмет при полном отсутствии строительства.
"""

from __future__ import annotations

import re

# Предмет — программный продукт.
_DIGITAL_SUBJECT_RE = re.compile(
    r"(?:\bсайт\w*\b|веб-?сайт\w*|\bwebsite\b|интернет-магазин\w*|лендинг\w*|"
    r"мобильн\w*\s+приложени\w*|приложени\w*\s+для\s+(?:iOS|Android|смартфон\w*)|"
    r"программн\w*\s+обеспечени\w*|программн\w*\s+продукт\w*|"
    r"информационн\w*\s+систем\w*|\bCRM\b|\bERP\b|чат-бот\w*|"
    r"разработк\w*\s+(?:сайт\w*|приложени\w*|программ\w*|порталa?\w*))",
    re.IGNORECASE,
)

# Признаки настоящего строительства. Намеренно не пересекаются со словом
# «строительный подряд»: иначе сама спорная квалификация подтверждала бы себя.
_CONSTRUCTION_SUBJECT_RE = re.compile(
    r"(?:строительств\w*|объект\w*\s+строительств\w*|реконструкци\w*|"
    r"капитальн\w*\s+(?:ремонт\w*|строительств\w*)|"
    r"инженерн\w*\s+изыскани\w*|геологическ\w*\s+изыскани\w*|"
    r"проектн\w*\s+документаци\w*|сметн\w*\s+документаци\w*|"
    r"строительн\w*\s+площадк\w*|земляны\w*\s+работ\w*|"
    r"генеральн\w*\s+подрядчик\w*|\bСНиП\b|\bСН\s+РК\b)",
    re.IGNORECASE,
)

# Квалификация, которую цифровой предмет не выдерживает.
_DESIGN_SURVEY_RE = re.compile(
    r"(?:проектн\w*\s+и\s+изыскательск\w*\s+работ\w*|проектно-изыскательск\w*|"
    r"изыскательск\w*\s+работ\w*|строительн\w*\s+подряд\w*|"
    r"подряд\w*\s+на\s+капитальн\w*\s+строительств\w*)",
    re.IGNORECASE,
)


def misclassification_blockers(case_context: str, lines: list[str]) -> list[str]:
    """Блокеры выпуска, когда вид договора противоречит предмету дела."""
    document = "\n".join(str(line or "") for line in lines or [])
    match = _DESIGN_SURVEY_RE.search(document)
    if not match:
        return []

    materials = "\n".join([case_context or "", document])
    if not _DIGITAL_SUBJECT_RE.search(materials):
        return []
    if _CONSTRUCTION_SUBJECT_RE.search(materials):
        return []

    return [
        f"вид договора определён как «{match.group(0)}», хотя предметом по материалам дела является "
        "разработка программного продукта (сайта, приложения, информационной системы); "
        "правила о проектных и изыскательских работах и о строительном подряде к нему не применяются"
    ]
