from __future__ import annotations

from dataclasses import dataclass
import re


@dataclass(frozen=True, slots=True)
class ClaimProfile:
    code: str
    label: str
    research_focus: str
    required_article_hints: tuple[str, ...] = ()
    search_context_size: str = "low"


@dataclass(frozen=True, slots=True)
class ContractProfile:
    code: str
    label: str
    research_focus: str
    search_context_size: str = "low"


def _has(text: str, *patterns: str) -> bool:
    return any(re.search(pattern, text, flags=re.IGNORECASE | re.DOTALL) for pattern in patterns)


def detect_claim_profile(case_context: str) -> ClaimProfile:
    """Route common Kazakhstan civil claims without an extra model call.

    This is only a search hint. The legal qualification itself must still be
    verified by the source-bound research pass before it can enter a document.
    """
    text = " ".join((case_context or "").split()).lower()

    if _has(
        text,
        r"\bзайм\w*\b",
        r"\bза[её]мщик\w*\b",
        r"\bзаймодав\w*\b",
        r"\bдал\w*\s+в\s+долг\b",
        r"\bодолж\w*\b",
        r"\bвернут\w*\s+деньг\w*\b",
        r"\bдолг\w*\b.{0,120}\bперевод\w*\b",
    ):
        return ClaimProfile(
            code="loan_debt",
            label="взыскание задолженности, возможные отношения займа",
            research_focus=(
                "Проверь материально-правовую квалификацию передачи денег и обязанности возврата. "
                "Обязательно открой действующую Особенную часть ГК РК и проверь применимость статей 715, 716 и 722 "
                "к конкретным фактам, включая форму займа, доказательства передачи денег и согласованный/несогласованный срок возврата. "
                "Не называй переписку или перевод заключенным договором займа, пока это не подтверждено применимыми нормами и фактами."
            ),
            required_article_hints=("715", "716", "722"),
        )

    if _has(text, r"\bпоставк\w*\b", r"\bпоставщик\w*\b"):
        return ClaimProfile(
            code="supply",
            label="спор из договора поставки",
            research_focus=(
                "Проверь действующие нормы ГК РК о поставке: наличие/содержание обязательства, срок и качество исполнения, "
                "оплату, последствия нарушения и допустимые способы защиты. Точные статьи определи по актуальной редакции Adilet."
            ),
        )

    if _has(text, r"\bоказан\w*\s+услуг\w*\b", r"\bисполнитель\w*\b.{0,120}\bзаказчик\w*\b"):
        return ClaimProfile(
            code="services",
            label="спор из возмездного оказания услуг",
            research_focus=(
                "Проверь действующие нормы ГК РК о возмездном оказании услуг: предмет, оплата, подтверждение исполнения, "
                "расторжение и последствия нарушения. Не переноси нормы подряда автоматически."
            ),
        )

    if _has(text, r"\bподряд\w*\b", r"\bподрядчик\w*\b"):
        return ClaimProfile(
            code="work_contract",
            label="спор из договора подряда",
            research_focus=(
                "Проверь действующие нормы ГК РК о подряде: предмет/результат работ, приемка, цена, сроки, недостатки и последствия нарушения."
            ),
        )

    if _has(text, r"\bаренд\w*\b", r"\bнаймодател\w*\b", r"\bарендатор\w*\b"):
        return ClaimProfile(
            code="lease",
            label="спор из аренды (имущественного найма)",
            research_focus=(
                "Проверь действующие нормы ГК РК об имущественном найме/аренде, обязанностях сторон, оплате, возврате имущества, "
                "расторжении и последствиях нарушения."
            ),
        )

    if _has(text, r"\bкупл\w*[- ]продаж\w*\b", r"\bпродавец\w*\b.{0,120}\bпокупател\w*\b"):
        return ClaimProfile(
            code="sale",
            label="спор из купли-продажи",
            research_focus=(
                "Проверь действующие нормы ГК РК о купле-продаже: передача товара, цена/оплата, качество, недостатки, "
                "возврат и иные применимые способы защиты."
            ),
        )

    if _has(text, r"\bпотребител\w*\b", r"\bзащит\w*\s+прав\w*\s+потребител\w*\b"):
        return ClaimProfile(
            code="consumer",
            label="защита прав потребителя",
            research_focus=(
                "Проверь применимые нормы действующего законодательства РК о защите прав потребителей и соответствующие нормы ГК РК. "
                "Отдельно проверь обязательный досудебный порядок, если он применим именно к этому требованию."
            ),
        )

    if _has(text, r"\bущерб\w*\b", r"\bвред\w*\b", r"\bвозмещен\w*\s+(?:ущерб|вред)\w*\b"):
        return ClaimProfile(
            code="damages",
            label="возмещение вреда/убытков",
            research_focus=(
                "Проверь правовое основание возмещения вреда или убытков, состав необходимых элементов ответственности, причинную связь, "
                "доказательства размера и применимые специальные правила. Не смешивай договорную и деликтную ответственность."
            ),
        )

    if _has(text, r"\bнеосновательн\w*\s+обогащен\w*\b", r"\bбез\s+основан\w*\s+(?:получил|удержива)\w*\b"):
        return ClaimProfile(
            code="unjust_enrichment",
            label="возврат неосновательного обогащения",
            research_focus=(
                "Проверь действующие нормы ГК РК о неосновательном обогащении, условия возврата, исключения и доказательства отсутствия правового основания."
            ),
        )

    if _has(text, r"\bтрудов\w*\b", r"\bработодатель\w*\b", r"\bувольнен\w*\b", r"\bзаработн\w*\s+плат\w*\b"):
        return ClaimProfile(
            code="labor",
            label="трудовой спор",
            research_focus=(
                "Проверь Трудовой кодекс РК и применимый порядок разрешения индивидуального трудового спора, включая обязательные предварительные процедуры, сроки и компетенцию."
            ),
            search_context_size="medium",
        )

    if _has(text, r"\bалимент\w*\b"):
        return ClaimProfile(
            code="alimony",
            label="взыскание алиментов",
            research_focus=(
                "Проверь Кодекс РК о браке (супружестве) и семье и ГПК РК: основание, размер/способ взыскания, процессуальную форму и необходимые доказательства."
            ),
            search_context_size="medium",
        )

    if _has(text, r"\bрасторжен\w*\s+брак\w*\b", r"\bразвод\w*\b"):
        return ClaimProfile(
            code="divorce",
            label="расторжение брака",
            research_focus=(
                "Проверь Кодекс РК о браке (супружестве) и семье и ГПК РК: когда требуется судебный порядок, компетенцию, содержание заявления и связанные требования."
            ),
            search_context_size="medium",
        )

    if _has(text, r"\bнаслед\w*\b", r"\bнаследств\w*\b"):
        return ClaimProfile(
            code="inheritance",
            label="наследственный спор",
            research_focus=(
                "Проверь действующие нормы наследственного права ГК РК, соответствующий способ защиты и процессуальные требования. "
                "Не подменяй иск нотариальной процедурой без проверки."
            ),
            search_context_size="medium",
        )

    if _has(text, r"\bправ\w*\s+собственност\w*\b", r"\bистребован\w*\s+имуществ\w*\b", r"\bвыселен\w*\b"):
        return ClaimProfile(
            code="property",
            label="вещно-правовой/жилищный имущественный спор",
            research_focus=(
                "Определи точный способ защиты вещного или жилищного права по фактам и проверь материальные нормы, субъектов, объект, регистрацию права и процессуальные требования."
            ),
            search_context_size="medium",
        )

    return ClaimProfile(
        code="general_civil",
        label="гражданско-правовой спор — точная квалификация определяется исследованием",
        research_focus=(
            "Сначала определи из фактов возможную материально-правовую природу требования, затем открой профильный действующий акт на Adilet. "
            "В VERIFIED не допускается общая ссылка на ГК без конкретной применимой нормы, если иск основан на конкретном договоре или внедоговорном обязательстве."
        ),
        search_context_size="medium",
    )


def detect_contract_profile(case_context: str) -> ContractProfile:
    text = " ".join((case_context or "").split()).lower()

    if _has(text, r"\bпоставк\w*\b", r"\bпоставщик\w*\b"):
        return ContractProfile("supply", "договор поставки", "Проверь нормы ГК РК о поставке, существенные условия, сроки, приемку, качество, оплату и ответственность.")
    if _has(text, r"\bоказан\w*\s+услуг\w*\b", r"\bуслуг\w*\b", r"\bисполнитель\w*\b"):
        return ContractProfile("services", "договор возмездного оказания услуг", "Проверь нормы ГК РК о возмездном оказании услуг, предмет, цену/оплату, приемку, срок, прекращение и ответственность.")
    if _has(text, r"\bподряд\w*\b", r"\bработ\w*\b.{0,80}\bзаказчик\w*\b"):
        return ContractProfile("work_contract", "договор подряда", "Проверь нормы ГК РК о подряде, предмет/результат, сроки, приемку, качество, цену и ответственность.")
    if _has(text, r"\bаренд\w*\b", r"\bнайм\w*\b"):
        return ContractProfile("lease", "договор имущественного найма (аренды)", "Проверь нормы ГК РК об имущественном найме: объект, срок, плата, передача/возврат, ремонт, расторжение и ответственность.")
    if _has(text, r"\bзайм\w*\b", r"\bодолж\w*\b", r"\bдать\s+в\s+долг\b"):
        return ContractProfile("loan", "договор займа", "Обязательно проверь действующую Особенную часть ГК РК, включая применимость статей 715, 716 и 722, форму, передачу суммы, срок возврата, вознаграждение и последствия нарушения.")
    if _has(text, r"\bкупл\w*[- ]продаж\w*\b", r"\bпродавец\w*\b", r"\bпокупател\w*\b"):
        return ContractProfile("sale", "договор купли-продажи", "Проверь нормы ГК РК о купле-продаже, предмет, цену, передачу, качество, риск, оплату и ответственность.")
    if _has(text, r"\bтрудов\w*\s+договор\w*\b", r"\bработодатель\w*\b.{0,100}\bработник\w*\b"):
        return ContractProfile("employment", "трудовой договор", "Проверь обязательные условия трудового договора по Трудовому кодексу РК, режим, оплату, место работы, срок, права/обязанности и прекращение.", "medium")
    if _has(text, r"\bагентск\w*\b", r"\bкомисси\w*\b", r"\bпоручени\w*\b"):
        return ContractProfile("intermediary", "посреднический договор", "Определи точный вид посреднического договора по фактам и проверь соответствующую главу ГК РК, полномочия, вознаграждение, отчетность и ответственность.", "medium")
    if _has(text, r"\bконфиденциальност\w*\b", r"\bnda\b"):
        return ContractProfile("confidentiality", "соглашение о конфиденциальности", "Проверь допустимость и содержание обязательств о конфиденциальности, применимые нормы о договорных обязательствах и защите охраняемой информации. Не придумывай неконкурентные ограничения.", "medium")

    return ContractProfile(
        "general",
        "гражданско-правовой договор — точный вид определяется исследованием",
        "Сначала определи вид договора по предмету и ролям сторон, затем проверь профильные нормы действующего законодательства РК, обязательную форму и существенные условия.",
        "medium",
    )
