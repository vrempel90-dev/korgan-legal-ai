def button(language: str, key: str) -> str:
    return BUTTONS[normalize_language(language)][key]


def button_values(key: str) -> tuple[str, str]:
    return BUTTONS[RU][key], BUTTONS[KK][key]


def tr(language: str, key: str, **kwargs: object) -> str:
    value = TEXTS[normalize_language(language)][key]
    return value.format(**kwargs) if kwargs else value
