from __future__ import annotations

import re

from korgan.legal.rk_catalog import CITATION_ACT_IDS

# Patterns are intentionally tied to the filing-facing short titles emitted by
# KORGAN.  This lets the legacy citation audit resolve the expanded local corpus
# without weakening any verification verdict.
_EXTRA_PATTERNS: tuple[tuple[str, str], ...] = (
    (r"аппк\s*рк|кас\s*рк|административн\w*\s+процедурно-процессуальн\w*\s+кодекс", "АППК РК"),
    (r"коап\s*рк|кодекс\w*.*административн\w*\s+правонаруш", "КоАП РК"),
    (r"упк\s*рк|уголовно-процессуальн\w*\s+кодекс", "УПК РК"),
    (r"ук\s*рк|уголовн\w*\s+кодекс", "УК РК"),
    (r"конституц\w*\s+(?:рк|республик\w*\s+казахстан)", "Конституция РК"),
    (r"кодекс\w*.*(?:о\s+браке|о\s+браке\s*\(супружестве\)|браке\s+и\s+семье)", "Кодекс РК о браке и семье"),
    (r"предпринимательск\w*\s+кодекс", "Предпринимательский кодекс РК"),
    (r"социальн\w*\s+кодекс", "Социальный кодекс РК"),
    (r"земельн\w*\s+кодекс", "Земельный кодекс РК"),
    (r"кодекс\w*.*здоровь\w*\s+народ", "Кодекс РК о здоровье народа"),
    (r"защит\w*\s+прав\w*\s+потребител", "Закон РК о защите прав потребителей"),
    (r"государственн\w*\s+закуп", "Закон РК о государственных закупках"),
    (r"исполнительн\w*\s+производств", "Закон РК об исполнительном производстве"),
    (r"жилищн\w*\s+отношен", "Закон РК о жилищных отношениях"),
    (r"банках\w*\s+и\s+банковск\w*\s+деятельност|закон\w*.*о\s+банках", "Закон РК о банках"),
    (r"микрофинансов\w*\s+деятельност", "Закон РК о микрофинансовой деятельности"),
    (r"коллекторск\w*\s+деятельност", "Закон РК о коллекторской деятельности"),
    (r"банкротств\w*\s+граждан|восстановлен\w*\s+платежеспособност", "Закон РК о банкротстве граждан"),
    (r"закон\w*.*нотариат", "Закон РК о нотариате"),
    (r"закон\w*.*образован", "Закон РК об образовании"),
    (r"государственн\w*\s+служб", "Закон РК о государственной службе"),
    (r"дорожн\w*\s+движен", "Закон РК о дорожном движении"),
    (r"адвокатск\w*\s+деятельност|юридическ\w*\s+помощ", "Закон РК об адвокатской деятельности"),
    (r"миграци\w*\s+населен", "Закон РК о миграции населения"),
    (r"язык\w*\s+в\s+республик\w*\s+казахстан|закон\w*.*о\s+языках", "Закон РК о языках"),
)


def install_extended_citation_audit() -> None:
    from korgan import citation_audit, client_safe_ui

    client_safe_ui._ACT_IDS.update(CITATION_ACT_IDS)
    existing = list(citation_audit._ACT_PATTERNS)
    labels = {act for _, act in existing}
    additions = [item for item in _EXTRA_PATTERNS if item[1] not in labels]
    if additions:
        citation_audit._ACT_PATTERNS = tuple(additions) + tuple(existing)
