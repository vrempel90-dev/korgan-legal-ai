from __future__ import annotations

from typing import Any

from korgan.universal_quality_service import UniversalQualityProductionService

_INSTALLED = False
_ORIGINAL_QUALITY_REPAIR = UniversalQualityProductionService._quality_repair

_SENIOR_DRAFTING_RULES = """
SENIOR LEGAL DRAFTING STANDARD:
10. Строй документ как практикующий юрист: установленный факт → подтверждающий материал → юридически значимый элемент → применимая VERIFIED норма → конкретный вывод/требование. Не перескакивай через звенья этой цепочки.
11. Не делай «россыпь статей». Каждая конкретная статья должна выполнять необходимую функцию для требования, возражения или условия. Не добавляй общую/декоративную норму, если профильная специальная норма уже достаточна.
12. Не превращай позицию стороны в установленный факт. Спорное утверждение оппонента обозначай как позицию/довод только когда оно есть в материалах; не придумывай признание долга, отказ, уведомление, получение, оплату, подписание, передачу или иной факт.
13. Разделяй материальное право и процесс: материальная норма должна обосновывать само требование/возражение, процессуальная — только форму, срок, подсудность, доказательства или порядок. Процессуальная статья не заменяет материальное основание.
14. Просительная/резолютивная часть должна быть исполнимой и математически согласованной с установленными суммами и детерминированными расчётами. Не добавляй самостоятельное требование, которого клиент не ставил и которое не следует из материалов/VERIFIED права.
15. Для договора проверяй жизненный цикл сделки: предмет и результат, роли и обязанности, порядок исполнения и приемки, оплату только в известных параметрах, ответственность только при подтверждённой ставке/основании, изменение/прекращение, уведомления и споры. Не выдумывай цену, процент, срок, дату, штраф, лимит, банковские реквизиты или персональные данные ради «полноты».
16. Для претензии/ответа/отзыва отвечай на каждое существенное требование или возражение из исходного материала по существу. Не создавай искусственный спор по вопросу, которого в материалах нет.
17. Пиши профессионально и сжато: без учебных объяснений, рекламных фраз, самооценки качества, повторов и цитирования закона ради объёма. Сначала точность и применимость, затем полнота, затем стиль.
""".strip()


def senior_drafting_rules() -> str:
    return _SENIOR_DRAFTING_RULES


async def _senior_quality_repair(
    self: UniversalQualityProductionService,
    *args: Any,
    **kwargs: Any,
) -> dict[str, Any]:
    existing = str(kwargs.get("extra_rules") or "").strip()
    kwargs["extra_rules"] = (
        f"{existing}\n{_SENIOR_DRAFTING_RULES}" if existing else _SENIOR_DRAFTING_RULES
    )
    return await _ORIGINAL_QUALITY_REPAIR(self, *args, **kwargs)


def install_senior_document_drafting_runtime() -> None:
    global _INSTALLED
    if _INSTALLED:
        return
    UniversalQualityProductionService._quality_repair = _senior_quality_repair  # type: ignore[assignment]
    _INSTALLED = True


install_senior_document_drafting_runtime()
