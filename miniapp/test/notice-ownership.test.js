/**
 * Уведомление принадлежит экрану, на котором началось действие.
 *
 * Кнопки навигации не гаснут во время работы, поэтому загрузку материалов или
 * отправку документа легко оставить в пути и уйти на другой экран. Ответ
 * приходил позже и писал сообщение туда, где пользователь уже находился: над
 * списком дел появлялось «Обработано файлов: 1», а над главной — отчёт о
 * доставке документа. Смена экрана гасит уведомление, но только то, которое
 * уже показано; написанное после перехода она погасить не может.
 *
 * Обработчик создан рендером того экрана, на котором его нажали, и потому знает
 * своё место; текущий экран читается через ссылку. Сам переход остаётся
 * исключением: он гасит уведомление всегда, иначе за ним тянулась бы чужая
 * ошибка.
 *
 * Экран проверки оплат из-за этого перестал грузить заказы «вдогонку» после
 * перехода — иначе его собственная ошибка загрузки считалась бы чужой и
 * пропадала. Экран загружает свои данные сам.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, '..', 'src', 'main.jsx'), 'utf8');

test('текущий экран доступен обработчику, созданному прежним рендером', () => {
  assert.match(app, /screenRef\.current = screen;/, 'ссылки на текущий экран нет');
});

test('сообщение пишется только с того экрана, на котором началось действие', () => {
  assert.match(
    app,
    /const setNotice = text => \{ if \(screenRef\.current === screen\)/,
    'уведомление пишется на любой экран, включая тот, на который пользователь ушёл',
  );
});

test('переход гасит уведомление всегда, минуя проверку экрана', () => {
  const line = app.split('\n').find(item => item.includes('const showScreen ='));
  assert.ok(line, 'переход между экранами не найден');
  assert.doesNotMatch(line, /setNotice\(''\)/, 'переход гасит уведомление через проверку своего же экрана');
  assert.match(line, /writeNotice\(''\)/, 'переход перестал гасить уведомление');
});

test('экран проверки оплат загружает заказы сам, а не вдогонку переходу', () => {
  const line = app.split('\n').find(item => item.includes('const openAdmin ='));
  assert.ok(line, 'вход в проверку оплат не найден');
  assert.doesNotMatch(
    line,
    /loadAdminOrders\(\)/,
    'заказы грузятся обработчиком прежнего экрана — его сообщение об ошибке пропадёт',
  );
  assert.match(app, /view === 'admin-payments'\) loadAdminOrders\(\)/, 'экран не загружает свои заказы');
});
