/**
 * Поколения действий: применяется только то, чего пользователь ещё ждёт.
 *
 * Запрос к серверу возвращается тогда, когда возвращается, а пользователь за
 * это время успевает нажать ещё раз, выбрать другое дело или уйти на другую
 * вкладку. Ответ, пришедший после этого, менять состояние не имеет права:
 * иначе на экране одного дела появляются материалы другого, а завершившийся
 * фоновый шаг выдёргивает пользователя обратно на экран, который он закрыл.
 *
 * `start()` открывает новое поколение и возвращает проверку «это всё ещё моё
 * действие». `invalidate()` закрывает текущее поколение, ничего не начиная, —
 * им пользуется смена экрана.
 */
export function createLatestAction() {
  let generation = 0;

  return {
    start() {
      generation += 1;
      const mine = generation;
      return () => generation === mine;
    },
    invalidate() {
      generation += 1;
    },
  };
}
