/**
 * Заголовок дела для списка: название документа без служебных пометок.
 *
 * Название документа пишет юридический конвейер, и пометка о недостающем
 * реквизите — «[ТРЕБУЕТ УТОЧНЕНИЯ: номер договора]» — в самом документе нужна:
 * она говорит юристу, что заполнить перед подачей. В списке дел человек читает
 * её как поломку приложения, поэтому чистится только отображаемая строка.
 * Название документа и его содержание не меняются.
 */

/** Пометки конвейера о недостающих данных — русская и казахская. */
const PLACEHOLDER = /\[(?:ТРЕБУЕТ\s+[^\]]*|НАҚТЫЛАУ\s+ҚАЖЕТ[^\]]*)\]/gi;
/** Технический заполнитель, попадающий в название вместо неизвестного значения. */
const UNKNOWN = /<?\bUNKNOWN\b>?/gi;
/** Номер, от которого после чистки остался только знак: «№» без самого номера. */
const EMPTY_NUMBER = /\s*(?:№|N[оo]\.?)\s*(?=$|[,.;)])/gi;

export function caseDisplayTitle(item, fallback = '') {
  const raw = String(item?.title || '');
  const cleaned = raw
    .replace(PLACEHOLDER, ' ')
    .replace(UNKNOWN, ' ')
    .replace(EMPTY_NUMBER, ' ')
    // Пробелы схлопываются после чистки, иначе на месте пометки остаётся дыра.
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,.;:])/g, '$1')
    .trim()
    // Знак препинания, оставшийся на конце строки без своего содержания.
    .replace(/[\s,;:—-]+$/, '')
    .trim();
  return cleaned || String(fallback || '').trim();
}

/**
 * Подпись карточки дела: только то, что в деле действительно есть.
 *
 * Материалы загружает человек, документ готовит KORGAN — это разные предметы,
 * и склеенное «0 файл(ов) · DOCX» читалось как противоречие. Дело, описанное
 * одним текстом, — обычный случай, и нулём файлов оно не «пустое».
 */
export function caseCardMeta(item, labels) {
  const parts = [String(item?.id || '').trim()];
  const materials = Number(item?.materials_count) || 0;
  if (materials > 0) parts.push(`${labels.materials}: ${materials}`);
  if (item?.has_document) parts.push(labels.documentReady);
  return parts.filter(Boolean).join(' · ');
}
