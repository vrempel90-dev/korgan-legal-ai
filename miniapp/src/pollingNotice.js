/**
 * Сообщение опроса убирается тем же опросом — и только своё.
 *
 * Опрос идёт, пока экран открыт, и сообщать ему есть о чём: связь пропала,
 * связь вернулась. Если сбой писать как обычное уведомление и не снимать, он
 * переживает восстановление и противоречит тому же экрану: прогресс идёт,
 * статус оплаты читается, а сверху висит «сервис недоступен». Если же снимать
 * уведомление на каждом удачном ответе — исчезнет и чужое, написанное
 * действием пользователя (ответ о принятом чеке живёт на экране оплаты).
 *
 * Отсюда правило: опрос заменяет показанное сообщение, только если показано
 * ровно то, что он написал сам. Чужое остаётся нетронутым, а своё он всё равно
 * запоминает — чтобы позже не снять чужое вместо него.
 */

/**
 * @param {{shown: string, owned: string, text: string}} state
 *   `shown` — что видно на экране, `owned` — что последним написал опрос,
 *   `text` — новое сообщение опроса (пустая строка означает «сбоя больше нет»).
 * @returns {{shown: string, owned: string}}
 */
export function pollingNoticeUpdate({ shown, owned, text }) {
  const next = String(text || '');
  const current = String(shown || '');
  return { shown: current === String(owned || '') ? next : current, owned: next };
}
